// Bảng cấu hình tính điểm (ScoringConfigEditor): logic thuần ở src/features/scoring/settings/editorModel.js, tương đương bản Vue.
import test from 'node:test'
import assert from 'node:assert/strict'
import * as M from '../src/features/scoring/settings/editorModel.js'
import { DEFAULT_RATES, defaultRow, makeRow } from '../src/lib/scoringConfig.js'

const def = { isCustomer: false, base: {}, customerName: '' }
const cus = (base = DEFAULT_RATES) => ({ isCustomer: true, base, customerName: 'Anh Dũng' })
const stateOf = (ctx, map, region = 'mb') => M.newState(ctx, M.loadWork(map), region)
const rowOf = (st, type) => st.rows.find((r) => r.type === type)
const edit = (st, type, patch) => ({ ...st, rows: st.rows.map((r) => (r.type === type ? { ...r, ...patch } : r)) })

test('mặc định: 15 cách đánh chuẩn theo nhóm Lô / Đề / Xiên / Lô trượt / Thần tài, giá lấy từ DEFAULT_RATES', () => {
  const st = stateOf(def, DEFAULT_RATES)
  assert.equal(st.rows.length, 15)
  assert.deepEqual(M.groupsOf(st.rows, false).map((g) => [g.id, g.rows.length]), [['lo', 3], ['de', 4], ['xien', 3], ['truot', 3], ['thantai', 2]])
  const lo = rowOf(st, 'lo')
  assert.equal(lo.price, String(DEFAULT_RATES['lo@mb'].price))
  assert.equal(lo.payout, String(DEFAULT_RATES['lo@mb'].payout))
  assert.equal(lo.symbolsInput, 'L, l, lo, lô, x, X')
  assert.equal(M.tagOf(def, st, lo), '')
})
test('khi đang sửa mọi nhóm đều hiện (kể cả nhóm trống "Kiểu đánh khác"), khi xem thì ẩn nhóm trống', () => {
  const st = stateOf(def, DEFAULT_RATES)
  assert.ok(!M.groupsOf(st.rows, false).some((g) => g.id === 'other'))
  assert.ok(M.groupsOf(st.rows, true).some((g) => g.id === 'other'))
})
test('giá trúng 0 (chưa nhập) bị đánh dấu đỏ, kiểu tự đặt thì không', () => {
  const st = stateOf(def, DEFAULT_RATES)
  const zero = st.rows.filter((r) => M.notSet(r)).map((r) => r.type)
  assert.ok(zero.length > 0 && zero.every((t) => !(Number(DEFAULT_RATES[`${t}@mb`].payout) > 0)))
  assert.equal(M.notSet({ ...rowOf(st, 'lo'), extra: true, payout: '0' }), false)
})
test('đổi giá một miền chỉ ghi khoá của miền đó; sửa lại bằng giá gốc thì bỏ khoá riêng', () => {
  // as saved by the server: every row already went through cfgOf/makeRow once
  const saved = M.committed(def, stateOf(def, DEFAULT_RATES))
  let st = stateOf(def, saved)
  const initial = M.initialOf(st.work)
  assert.equal(M.isDirty(def, st, initial), false)
  st = edit(st, 'lo', { price: '25000' })
  assert.ok(M.isDirty(def, st, initial))
  const w = M.committed(def, st)
  assert.equal(w['lo@mb'].price, 25000)
  assert.equal(w['lo@mt'].price, DEFAULT_RATES['lo@mt'].price)
  const back = edit({ ...st, work: w }, 'lo', { price: String(DEFAULT_RATES['lo@mb'].price) })
  assert.equal(M.isDirty(def, back, initial), false)
})
test('đổi miền: lưu các dòng đã sửa vào bảng, dòng sai thì chặn và báo lỗi', () => {
  let st = stateOf(def, DEFAULT_RATES)
  st = edit(st, 'lo', { price: '0' })
  const bad = M.switchRegion(def, st, 'mt')
  assert.equal(bad.error, 'Giá tiền/1 điểm của "Bao lô 2 số" không hợp lệ')
  assert.equal(bad.st.region, 'mb')
  st = edit(st, 'lo', { price: '30000' })
  const ok = M.switchRegion(def, st, 'mt')
  assert.equal(ok.error, '')
  assert.equal(ok.st.region, 'mt')
  assert.equal(ok.st.work['lo@mb'].price, 30000)
  assert.equal(rowOf(ok.st, 'lo').price, String(DEFAULT_RATES['lo@mt'].price))
})
test('kiểm tra hợp lệ: giá trúng âm, lấy số thiếu giải / sai chữ số, ký hiệu sai hoặc trùng', () => {
  const st = stateOf(def, DEFAULT_RATES)
  assert.equal(M.validate(st), '')
  assert.equal(M.validate(edit(st, 'dau', { payout: '-1' })), 'Giá trúng/1 điểm của "Đầu" không hợp lệ')
  assert.equal(M.validate(edit(st, 'dau', { srcTiers: [], srcPos: 'last' })), '"Đầu": chọn ít nhất một giải để lấy số')
  assert.equal(M.validate(edit(st, 'dau', { srcDigits: 9 })), '"Đầu": số chữ số từ 1 đến 6')
  assert.equal(M.validate(edit(st, 'duoi', { symbolsInput: 'c, 12' })), 'Ký hiệu "12" của "Đuôi" chỉ được gồm chữ cái (tối đa 12 ký tự)')
  // "đ" của Đầu và "d" của Đuôi cùng một ký hiệu sau khi bỏ dấu
  assert.equal(M.validate(edit(st, 'duoi', { symbolsInput: 'c, D' })), 'Ký hiệu "D" đang dùng cho cả "Đầu" và "Đuôi"')
})
test('"lấy số" đổi khác mặc định thì mới được lưu; Về mặc định trả lại', () => {
  let st = stateOf(def, DEFAULT_RATES)
  const lo = rowOf(st, 'lo')
  assert.equal(M.srcChanged(lo, 'mb'), false)
  assert.equal(M.srcCaption(lo, 'mb'), '2 số cuối của cả 27 lô')
  st = edit(st, 'lo', { srcDigits: 3 })
  assert.equal(M.srcChanged(rowOf(st, 'lo'), 'mb'), true)
  assert.equal(M.srcCaption(rowOf(st, 'lo'), 'mb'), '3 số cuối của cả 27 lô')
  assert.equal(M.cfgOf(rowOf(st, 'lo'), 'mb').source.digits, 3)
  st = edit(st, 'lo', M.resetSrcPatch(rowOf(st, 'lo'), 'mb'))
  assert.equal(M.srcChanged(rowOf(st, 'lo'), 'mb'), false)
  assert.equal(M.fieldsOf(rowOf(st, 'xien2')).position, false)
  assert.equal(M.fieldsOf(rowOf(st, 'tai_xiu')).digits, false)
})
test('xoá một cách đánh chuẩn = đánh dấu bỏ, ẩn khỏi bảng và có thể khôi phục', () => {
  let st = stateOf(def, DEFAULT_RATES)
  assert.match(M.removeMessage(def, 'mb', rowOf(st, 'dau')), /^Xoá "Đầu" khỏi bảng Miền Bắc\? /)
  st = M.removeRow(def, st, rowOf(st, 'dau'))
  assert.equal(rowOf(st, 'dau'), undefined)
  assert.deepEqual(st.work['dau@mb'], { disabled: true })
  assert.deepEqual(M.restorable(def, st, 'de').map((k) => k.kind), ['dau'])
  const back = M.addRow(def, st, { ...M.openAddForm(def, st, 'de') })
  assert.equal(back.closed, true)
  assert.ok(rowOf(back.st, 'dau'))
  assert.equal(back.st.work['dau@mb'], undefined)
})
test('thêm cách đánh mới: kiểm tra ký hiệu, trùng, giá; hợp lệ thì thành dòng "Kiểu đánh khác"', () => {
  const st = stateOf(def, DEFAULT_RATES)
  const form = { ...M.openAddForm(def, st, 'other'), name: 'Đề 3 số', symbol: 'D3' }
  assert.equal(form.pick, 'new')
  assert.equal(M.addRow(def, st, { ...form, symbol: 'đề' }).error, 'Ký hiệu chỉ gồm chữ không dấu hoặc số (tối đa 12 ký tự)')
  assert.equal(M.addRow(def, st, { ...form, symbol: 'lo' }).error, 'Ký hiệu này đã có')
  assert.equal(M.addRow(def, st, { ...form, price: '0' }).error, 'Giá tiền phải lớn hơn 0, giá trúng không âm')
  const res = M.addRow(def, st, { ...form, tiers: 'all', digits: 3 })
  assert.equal(res.closed, true)
  const r = rowOf(res.st, 'd3')
  assert.ok(r.extra)
  assert.equal(r.label, 'Đề 3 số')
  assert.equal(r.group, 'other')
  assert.equal(r.srcDigits, 3)
  assert.equal(r.srcTiers.length, 8)
  assert.equal(res.st.work['d3@mb'].kind, 'custom')
  // trùng với dòng vừa thêm
  assert.equal(M.addRow(def, res.st, form).error, 'Ký hiệu này đã có')
})
test('kiểu cũ "de" và "3-càng" trùng chuẩn mới chỉ hiện một (dòng chuẩn), dữ liệu cũ vẫn giữ', () => {
  const map = { ...DEFAULT_RATES, de: makeRow({ kind: 'custom', price: 1, payout: 70 }), '3-càng': makeRow({ kind: 'custom', price: 1, payout: 900 }) }
  const st = stateOf(def, map)
  assert.equal(st.rows.filter((r) => r.extra).length, 0)
  assert.equal(st.rows.length, 15)
  const res = M.prepareSave(def, st)
  assert.ok(res.map.de && res.map['3-càng'])
})
test('khách: dòng theo mặc định chung, sửa thì "Riêng", "Theo chung" trả lại', () => {
  const ctx = cus()
  let st = stateOf(ctx, {})
  assert.equal(M.tagOf(ctx, st, rowOf(st, 'lo')), 'Mặc định')
  assert.equal(M.noteOf(ctx, st.work), 'Đang dùng cấu hình mặc định')
  st = edit(st, 'lo', { price: '99999' })
  assert.equal(M.hasOwn(ctx, st, rowOf(st, 'lo')), true)
  assert.equal(M.tagOf(ctx, st, rowOf(st, 'lo')), 'Riêng')
  const w = M.committed(ctx, st)
  assert.equal(w['lo@mb'].price, 99999)
  assert.equal(Object.keys(w).length, 1) // chỉ dòng đã đổi được lưu
  st = M.resetRow(ctx, { ...st, work: w }, rowOf(st, 'lo'))
  assert.equal(rowOf(st, 'lo').price, String(DEFAULT_RATES['lo@mb'].price))
  assert.equal(M.noteOf(ctx, st.work), 'Đang dùng cấu hình mặc định')
})
test('khách: bỏ dùng một dòng ở một miền, bật lại; đếm mục riêng; chấm ở tab miền', () => {
  const ctx = cus()
  let st = stateOf(ctx, {})
  st = M.toggleOff(ctx, st, rowOf(st, 'cang4'))
  assert.equal(rowOf(st, 'cang4').off, true)
  assert.equal(M.tagOf(ctx, st, rowOf(st, 'cang4')), 'Không dùng')
  assert.deepEqual(st.work['cang4@mb'], { disabled: true })
  assert.equal(M.noteOf(ctx, st.work), '1 mục riêng')
  assert.equal(M.regionHasOverride(ctx, st.work, 'mb'), true)
  assert.equal(M.regionHasOverride(ctx, st.work, 'mt'), false)
  assert.equal(M.regionHasOverride(def, st.work, 'mb'), false)
  st = M.toggleOff(ctx, st, rowOf(st, 'cang4'))
  assert.equal(rowOf(st, 'cang4').off, false)
  assert.equal(st.work['cang4@mb'], undefined)
})
test('khách: dòng tài khoản đã xoá thì khách không thấy; xoá bỏ qua dòng "tắt" khi kiểm tra', () => {
  const base = { ...DEFAULT_RATES, 'dau@mb': { disabled: true } }
  const ctx = cus(base)
  const st = stateOf(ctx, {})
  assert.equal(rowOf(st, 'dau'), undefined)
  assert.deepEqual(M.restorable(ctx, st, 'de').map((k) => k.kind), [])
  const off = M.toggleOff(ctx, stateOf(ctx, {}), rowOf(st, 'lo'))
  assert.equal(M.validate({ ...off, rows: off.rows.map((r) => (r.off ? { ...r, price: '0' } : r)) }), '')
})
test('lưu mặc định: điền đủ mọi cách đánh mọi miền (tài khoản cũ chỉ có Đề / Lô); khách: map rỗng = dùng mặc định', () => {
  const old = { lo: makeRow({ kind: 'lo', price: 23000, payout: 80000 }) }
  const st = stateOf(def, old)
  const res = M.prepareSave(def, st)
  assert.equal(res.error, '')
  assert.ok(res.map.lo)
  for (const r of ['mb', 'mt', 'mn']) for (const k of ['lo', 'dau', 'xien2', 'chan_le']) assert.ok(res.map[`${k}@${r}`] || res.map[k])
  const c = cus()
  assert.deepEqual(M.prepareSave(c, stateOf(c, {})).map, {})
  assert.equal(M.savedNotice(c, null), 'Anh Dũng đang dùng cấu hình mặc định')
  assert.equal(M.savedNotice(c, { x: 1 }), 'Đã lưu cấu hình riêng cho Anh Dũng')
  assert.equal(M.savedNotice(def, {}), 'Đã lưu cấu hình mặc định')
})
